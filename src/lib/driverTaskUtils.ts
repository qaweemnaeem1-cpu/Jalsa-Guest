import { supabase } from '@/lib/supabase';
import type { Guest, DriverTaskPriority } from '@/types';

// ── priority helpers ──────────────────────────────────────────────────────────

/**
 * Compute auto-priority for a task:
 * - VIP  → guest designation contains "National Amir" or "Nazir"
 * - Urgent → task is within 2 hours from now
 * - Normal → everything else
 */
export function getAutoPriority(
  guestDesignation?: string,
  scheduledDate?: string,
  scheduledTime?: string,
): DriverTaskPriority {
  if (guestDesignation) {
    const d = guestDesignation.toLowerCase();
    if (d.includes('national amir') || d.includes('nazir')) return 'vip';
  }
  if (scheduledDate && scheduledTime) {
    const taskMs  = new Date(`${scheduledDate}T${scheduledTime}:00`).getTime();
    const nowMs   = Date.now();
    const diffHrs = (taskMs - nowMs) / 3_600_000;
    if (diffHrs >= 0 && diffHrs <= 2) return 'urgent';
  }
  return 'normal';
}

// ── batch pickup helpers ──────────────────────────────────────────────────────

/**
 * Find an existing suggested airport_pickup task for the same flight + date + location.
 * Returns the task row (id, passenger_count) or null.
 */
async function findExistingFlightTask(
  taskType: 'airport_pickup' | 'airport_dropoff',
  flightNumber: string,
  scheduledDate: string,
  locationName: string,
) {
  const { data } = await supabase
    .from('driver_tasks')
    .select('id, passenger_count, guest_name')
    .eq('task_type', taskType)
    .eq('flight_number', flightNumber)
    .eq('scheduled_date', scheduledDate)
    .eq('location', locationName)
    .eq('is_suggestion', true)
    .neq('status', 'cancelled')
    .maybeSingle();
  return data as { id: string; passenger_count: number | null; guest_name: string | null } | null;
}

/**
 * Add a passenger record to driver_task_passengers (best-effort).
 */
async function addPassenger(taskId: string, guest: Guest) {
  await supabase.from('driver_task_passengers').insert({
    task_id:    taskId,
    guest_id:   guest.id,
    guest_name: guest.fullName,
    guest_phone: null,
    guest_photo: null,
  });
}

